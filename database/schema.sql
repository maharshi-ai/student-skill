CREATE DATABASE IF NOT EXISTS student_internship;
USE student_internship;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, full_name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL,
 role ENUM('STUDENT','ADMIN') NOT NULL DEFAULT 'STUDENT',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS student_profiles (
 user_id BIGINT PRIMARY KEY, phone VARCHAR(25), college VARCHAR(160),
 department VARCHAR(120), course VARCHAR(120), academic_year TINYINT, cgpa DECIMAL(4,2),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 CHECK(cgpa IS NULL OR (cgpa>=0 AND cgpa<=10))
);
CREATE TABLE IF NOT EXISTS skills (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL UNIQUE, category VARCHAR(80) NOT NULL
);
CREATE TABLE IF NOT EXISTS student_skills (
 student_id BIGINT NOT NULL, skill_id BIGINT NOT NULL,
 proficiency ENUM('BEGINNER','INTERMEDIATE','ADVANCED') NOT NULL,
 experience_years DECIMAL(4,1) NOT NULL DEFAULT 0, PRIMARY KEY(student_id,skill_id),
 FOREIGN KEY(student_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(skill_id) REFERENCES skills(id) ON DELETE RESTRICT
);
CREATE TABLE IF NOT EXISTS internships (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, title VARCHAR(160) NOT NULL, company VARCHAR(160) NOT NULL,
 description TEXT NOT NULL, required_skills TEXT, location VARCHAR(160), duration VARCHAR(80),
 stipend DECIMAL(10,2), deadline DATE NOT NULL,
 status ENUM('OPEN','CLOSED','ARCHIVED') NOT NULL DEFAULT 'OPEN',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_internship_status_deadline(status,deadline)
);
CREATE TABLE IF NOT EXISTS applications (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, student_id BIGINT NOT NULL, internship_id BIGINT NOT NULL,
 cover_letter TEXT NOT NULL,
 status ENUM('PENDING','UNDER_REVIEW','ACCEPTED','REJECTED') NOT NULL DEFAULT 'PENDING',
 admin_feedback TEXT, applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_student_internship(student_id,internship_id),
 FOREIGN KEY(student_id) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY(internship_id) REFERENCES internships(id) ON DELETE RESTRICT,
 INDEX idx_app_status(status)
);
